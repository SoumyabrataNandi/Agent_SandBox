//! Verifies the pinned interpreter assets and generates `include_bytes!` bindings.
//!
//! No network access happens here (run `python scripts/fetch-assets.py` first). The assets
//! directory defaults to `<workspace>/assets/vendor` and can be overridden with
//! `SANDBOXD_ASSETS_DIR` for offline / air-gapped builds.

use std::{
    collections::BTreeMap,
    env, fs,
    io::Read,
    path::{Path, PathBuf},
};

use serde::Deserialize;
use sha2::{Digest, Sha256};

#[derive(Deserialize)]
struct Asset {
    version: String,
    url: String,
    file: String,
    sha256: String,
    license: String,
}

fn sha256_file(path: &Path) -> String {
    let mut f = fs::File::open(path).unwrap_or_else(|e| panic!("open {}: {e}", path.display()));
    let mut h = Sha256::new();
    let mut buf = vec![0u8; 1 << 20];
    loop {
        let n = f.read(&mut buf).expect("read asset");
        if n == 0 {
            break;
        }
        h.update(&buf[..n]);
    }
    hex::encode(h.finalize())
}

fn main() {
    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let workspace = crate_dir.join("../..");
    let manifest_path = workspace.join("assets/manifest.toml");
    let vendor = env::var_os("SANDBOXD_ASSETS_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| workspace.join("assets/vendor"));

    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rerun-if-env-changed=SANDBOXD_ASSETS_DIR");

    let manifest: BTreeMap<String, Asset> =
        toml::from_str(&fs::read_to_string(&manifest_path).expect("read assets/manifest.toml"))
            .expect("parse assets/manifest.toml");

    let mut out = String::from("// @generated by sandboxd-assets/build.rs\n");
    for key in ["python", "javascript"] {
        let a = manifest
            .get(key)
            .unwrap_or_else(|| panic!("assets/manifest.toml is missing [{key}]"));
        let path = vendor.join(&a.file);
        println!("cargo:rerun-if-changed={}", path.display());
        if !path.exists() {
            panic!(
                "\n\nmissing guest asset {}\n  run: python scripts/fetch-assets.py\n  (or set SANDBOXD_ASSETS_DIR to a directory containing it)\n",
                path.display()
            );
        }
        let actual = sha256_file(&path);
        if actual != a.sha256.to_lowercase() {
            panic!(
                "\n\nSHA-256 mismatch for {}\n  expected {}\n  actual   {actual}\nRefusing to embed an unverified interpreter.\n",
                path.display(),
                a.sha256
            );
        }
        let upper = key.to_uppercase();
        let abs = fs::canonicalize(&path).expect("canonicalize asset path");
        out.push_str(&format!(
            "pub const {upper}: Asset = Asset {{ name: {key:?}, version: {:?}, url: {:?}, sha256: {:?}, license: {:?}, bytes: include_bytes!({:?}) }};\n",
            a.version, a.url, a.sha256, a.license, abs
        ));
    }

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("assets.rs");
    fs::write(dest, out).expect("write generated assets.rs");
}
